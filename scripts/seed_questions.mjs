async function runSeed() {
  console.log(`Preparing to replace question bank with ${NEW_QUESTIONS.length} new questions...`)

  // 1. Delete dependent records first to maintain referential integrity
  const { error: delCQError } = await supabase.from('competition_questions').delete().neq('id', '00000000-0000-0000-0000-000000000000')
  if (delCQError) console.warn('Warning deleting competition_questions:', delCQError)

  const { error: delAQError } = await supabase.from('attempt_questions').delete().neq('id', '00000000-0000-0000-0000-000000000000')
  if (delAQError) console.warn('Warning deleting attempt_questions:', delAQError)

  const { error: delRespError } = await supabase.from('quiz_responses').delete().neq('id', '00000000-0000-0000-0000-000000000000')
  if (delRespError) console.warn('Warning deleting quiz_responses:', delRespError)

  // 2. Clear old questions in question_bank
  const { error: delQBError } = await supabase.from('question_bank').delete().neq('id', '00000000-0000-0000-0000-000000000000')
  if (delQBError) {
    console.error('Error clearing question_bank:', delQBError)
    process.exit(1)
  }
  console.log('Old question bank cleared successfully.')

  // 3. Insert new questions
  const { data: inserted, error: insError } = await supabase.from('question_bank').insert(NEW_QUESTIONS).select('id, question_text')
  if (insError) {
    console.error('Error inserting new questions:', insError)
    process.exit(1)
  }

  console.log(`Successfully inserted ${inserted.length} new AMR questions into question_bank!`)
}

runSeed().catch((err) => {
  console.error('Seed script encountered error:', err)
  process.exit(1)
})
